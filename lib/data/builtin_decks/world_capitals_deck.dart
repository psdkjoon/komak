Deck buildWorldCapitalsDeck() {
  final List<Flashcard> cards = <Flashcard>[
    for (final List<String> entry in _countries)
      Flashcard(front: entry[0], back: entry[1], groupId: entry[2]),
  ];

  return Deck(
    title: 'World Capitals',
    description:
        'All 196 countries and their capital cities, grouped by continent.',
    accentColorValue: 0xFFA6E3A1,
    iconKey: 'public',
    cards: cards,
    enabledTypes: <QuestionType>{
      QuestionType.multipleChoice,
      QuestionType.timed,
      QuestionType.textField,
      QuestionType.matching,
      QuestionType.oddOneOut,
      QuestionType.trueFalse,
      QuestionType.reverseChoice,
      QuestionType.scramble,
      QuestionType.hintTyping,
      QuestionType.selfCheck,
      QuestionType.memory,
    },
    builtInKey: 'capitals',
    practiceLength: 15,
  );
}
